"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
SERIES = ["market", "large", "small"]
FITTED = ["AR(1)", "Ridge", "Boosting"]
EARLY, LATE = ["1935-1969", "1970-1999"], ["2000-2012", "2013-2026"]


def headline(m: dict) -> str:
    mk, sm = m["series"]["market"], m["series"]["small"]
    era = lambda s, e, mod: m["series"][s]["eras"][e]["models"][mod]
    checks = {
        "before 2000 the market is predictable by AR(1) and by boosting":
            all(era("market", e, x)["r2_oos"] > 0 and era("market", e, x)["clark_west_t"] > 3
                for e in EARLY for x in ("AR(1)", "Boosting")),
        "since 2000 ridge and boosting are worse than predicting zero on the market and large stocks":
            all(era(s, e, x)["r2_oos"] < 0 for s in ("market", "large") for e in LATE for x in ("Ridge", "Boosting")),
        "boosting never beats AR(1) significantly on the market":
            all(era("market", e, "Boosting")["vs_ar1_t"] > -1.96 for e in EARLY + LATE),
        "boosting is significantly less accurate than AR(1) on the market over the full sample":
            mk["full"]["models"]["Boosting"]["vs_ar1_t"] > 1.96,
        "since 2000 no model beats buy and hold after costs on the market":
            all(era("market", e, x)["net_minus_buy_hold"]["lo"] <= 0 for e in LATE for x in FITTED),
        "predictability left the largest stocks first, then the market, then the smallest stocks, the market's in the 1990s":
            m["series"]["large"]["ar1_trailing_r2_first_below_zero"] < mk["ar1_trailing_r2_first_below_zero"]
            < sm["ar1_trailing_r2_first_below_zero"] and "1995" <= mk["ar1_trailing_r2_first_below_zero"] < "2000",
        "small stocks from 1970 to 1999 are the extreme case":
            era("small", "1970-1999", "AR(1)")["r2_oos"] > 0.10,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    s = m["sample"]
    e70, l13 = mk["eras"]["1970-1999"], mk["eras"]["2013-2026"]
    worst = min(era("market", e, "Boosting")["r2_oos"] for e in LATE)
    return (
        f"**Answer, from {s['n_forecasts']:,} out-of-sample daily forecasts between {s['first_forecast'][:4]} and "
        f"{s['last_forecast'][:4]}: it could until the late 1990s, and a one-variable regression did it as well as "
        f"machine learning. Since 2000 it cannot.** From 1970 to 1999 a regression on yesterday's return explains "
        f"{e70['models']['AR(1)']['r2_oos']:.1%} of next-day market variance out of sample, and gradient boosting "
        f"with {s['n_features']} features explains {e70['models']['Boosting']['r2_oos']:.1%}. Since 2000 boosting "
        f"is worse than always predicting zero in both later eras (R2 as low as {worst:.1%}), and over the full "
        f"sample it is significantly less accurate than the one-variable regression "
        f"(t = {mk['full']['models']['Boosting']['vs_ar1_t']:.1f}). On the market no model beats buy and hold after "
        f"{s['cost_bps']:.0f} bps costs in either era since 2000. The old predictability was strongest where "
        f"prices were stalest: {sm['eras']['1970-1999']['models']['AR(1)']['r2_oos']:.0%} for the smallest stocks "
        f"from 1970 to 1999, which is a sign of prices that had not yet traded, not of money left on the table."
    )


def accuracy_table(m: dict, s: str) -> list[str]:
    b = m["series"][s]
    out = [f"**{b['label']}**", "", "| Era | Days | Autocorrelation | " + " | ".join(FITTED) + " |",
           "|---|---|---|" + "---|" * len(FITTED)]
    for name, blk in list(b["eras"].items()) + [("All", b["full"])]:
        cells = [f"{blk['models'][x]['r2_oos']:+.2%} ({blk['models'][x]['clark_west_t']:+.1f})" for x in FITTED]
        out.append(f"| {name} | {blk['n_days']:,} | {blk['autocorr_1']:+.2f} | " + " | ".join(cells) + " |")
    return out + [""]


def results(m: dict) -> str:
    s = m["sample"]
    out = [f"Forecasts {s['first_forecast']} to {s['last_forecast']} ({s['years']:.0f} years). Each model is trained "
           f"on the latest {s['train_days']:,} days and refitted every {s['refit_days']} days, {s['n_refits']} "
           f"times per series.", "",
           "### Accuracy", "",
           "Out-of-sample R2 against always predicting zero, with the Clark-West t-statistic in brackets "
           "(above 1.65 is significant at 5%, one sided). Autocorrelation is the plain correlation of each "
           "day's return with the day before.", ""]
    for x in SERIES:
        out += accuracy_table(m, x)
    out += ["**When it went away.** Trailing ten year R2 of the AR(1) forecast, as in the figure", "",
            "| Series | Peak | Ten years ending | First below zero |", "|---|---|---|---|"]
    for x in SERIES:
        b = m["series"][x]
        out.append(f"| {b['label']} | {b['ar1_trailing_r2_peak']:.1%} | {b['ar1_trailing_r2_peak_date'][:4]} | "
                   f"{b['ar1_trailing_r2_first_below_zero'][:4]} |")
    out += ["", "### Does machine learning add anything to one lag?", "",
            "Diebold-Mariano t-statistic of squared error against the AR(1) forecast. Negative means more "
            "accurate than AR(1), positive less; beyond 1.96 either way is significant.", "",
            "| Series | Model | " + " | ".join(EARLY + LATE) + " | All |", "|---|---|---|---|---|---|---|"]
    for x in SERIES:
        b = m["series"][x]
        for mod in ("Ridge", "Boosting"):
            cells = [f"{b['eras'][e]['models'][mod]['vs_ar1_t']:+.1f}" for e in EARLY + LATE]
            out.append(f"| {b['label']} | {mod} | " + " | ".join(cells) + f" | {b['full']['models'][mod]['vs_ar1_t']:+.1f} |")
    out += ["", "### Trading it", "",
            f"Hold the series when the forecast is positive, cash otherwise, {s['cost_bps']:.0f} bps per unit "
            f"traded. Each cell is the strategy's Sharpe ratio minus buy and hold's, with a 95% bootstrap "
            f"interval. The last column is the cost at which the full-sample edge over buy and hold disappears.", "",
            "| Series | Model | " + " | ".join(EARLY + LATE) + " | Break-even cost, all years |",
            "|---|---|---|---|---|---|---|"]
    for x in SERIES:
        b = m["series"][x]
        for mod in ("AR(1)", "Boosting"):
            cells = []
            for e in EARLY + LATE:
                d = b["eras"][e]["models"][mod]["net_minus_buy_hold"]
                cells.append(f"{d['diff']:+.2f} [{d['lo']:+.2f}, {d['hi']:+.2f}]")
            out.append(f"| {b['label']} | {mod} | " + " | ".join(cells) +
                       f" | {b['full']['models'][mod]['break_even_cost_bps']:.0f} bps |")
    mk = m["series"]["market"]
    out += ["", "Buy and hold Sharpe ratio of the market by era: " +
            ", ".join(f"{mk['eras'][e]['buy_hold_sharpe']:.2f} ({e})" for e in EARLY + LATE) +
            f". The strategies trade about {mk['full']['models']['AR(1)']['trades_per_year']:.0f} times a year."]
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
